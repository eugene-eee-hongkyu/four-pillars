export function buildInterpretPremiumPart1Prompt(ctx: InterpretPremiumContext): string {
  const spec = gradeSpec(ctx.grade);
  const sharedCtx = buildSharedManseContext(ctx);

  const lines = [
    sharedCtx,
    `[Part 1 분량] ${spec.sentenceRangePart1}`,
    ``,
    `[작업 — Part 1 본질·인성·관계·즉시 행동 10 섹션]`,
    `${ctx.childNickname}의 정밀 학운 Part 1을 어머니께 풀어주세요.`,
    `§0 TL;DR + §1~§10 (시작·본질·강점·약점·환경·훈육·건강·엄마합·아빠합·강요금지) 순서 준수.`,
    `신규 4 섹션 (§7 건강·§8 엄마합·§9 아빠합·§10 강요금지)은 system prompt 명리 근거 인용 가이드를 그대로 활용.`,
    `격국·12운성·납음·합충형 모두 활용 / "보여요·나와요" 어미 자연 / 사주 용어는 평이한 풀이 곁들임.`,
    `**Part 2 영역(학원·진로·해외·학교 등)은 절대 언급 ✗** — Part 2에서 풀이.`,
    ctx.childManse.hourPillar ? `` : `시(時)주 미입력 — 시주 관련 추측 금지, 면책 톤 유지.`,
  ].filter(Boolean);

  return lines.join('\n');
}
